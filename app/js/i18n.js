export function t(lang, key, vars = {}) {
  const s = (S[lang] && S[lang][key]) || S.en[key] || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

// Numbers: keep Western digits for readability on site boards; swap if your users prefer native digits.
export function num(lang, v, digits = 1) { return Number(v).toFixed(digits); }
